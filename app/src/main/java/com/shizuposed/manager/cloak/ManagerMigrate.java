package com.shizuposed.manager.cloak;

import android.content.Context;
import android.database.sqlite.SQLiteDatabase;
import android.util.Log;

import java.io.BufferedOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import java.util.zip.ZipInputStream;
import java.util.zip.ZipOutputStream;

/**
 * ManagerMigrate
 *
 * Packages the current install's settings, signing keystores,
 * and module database into a zip that ManagerCloak embeds in
 * the rebuilt APK. On first launch of the new package,
 * importIfNeeded() reads that zip and restores the data.
 *
 * The migrate payload is deliberately narrow: the things that
 * are user state. The dex, native libs, and shell-side caches
 * are re-deployed by ShizuPosedService on first launch, so they
 * don't need to be carried across.
 *
 * THE TWO KEYSTORES
 * -----------------
 * files/keystore.bks is the MODULE-signing keystore (user
 * state, generated by the user). It is carried across so the
 * modules the user installed stay verifiable on the other side.
 *
 * files/cloak-install.p12 is the PER-INSTALL cloak signing key
 * (generated on the first cloak by ManagerCloak.ensurePerInstallKey).
 * It is carried across so the cloaked install and the restored
 * standard install share the same signing key. Without this,
 * every cloak and every unhide would generate a new key, and
 * the signature would change on every cycle — which defeats
 * the point of having a per-install key (one stable identity
 * per install cycle, not a new one each time).
 *
 * THE SETTINGS FILE IS THE CARRIER FOR original_package_name
 * -----------------------------------------------------------
 * ShizuPosedManagerApp.onCreate() writes original_package_name
 * into shared_prefs/shizuposed_settings.xml on first launch.
 * Because ManagerMigrate packages that file, the seed survives
 * both Hide and Unhide with no change to this class.
 *
 * IMPORT IS IDEMPOTENT
 * --------------------
 * A crash mid-import leaves no marker, so the next launch
 * re-imports and overwrites the partial files with the full
 * payload. That is safe because every write truncates and
 * rewrites the destination; there is no append or merge.
 *
 * The cloak-install.p12 write happens before the marker is
 * created, so a partial import cannot leave a half-written
 * key file with a "done" marker. If the import fails before
 * the marker, the next launch retries it.
 */
public final class ManagerMigrate {

    private static final String TAG = "ManagerMigrate";
    private static final String MARKER = ".cloak_migrate_done";

    private static final String ENTRY_PREFS = "settings.xml";
    private static final String ENTRY_MODULE_KEYSTORE = "keystore.bks";
    private static final String ENTRY_CLOAK_KEYSTORE = "cloak-install.p12";
    private static final String ENTRY_DB = "modules_config.db";
    private static final String ENTRY_DB_WAL = "modules_config.db-wal";
    private static final String ENTRY_DB_SHM = "modules_config.db-shm";

    /** The SharedPreferences file name used by ShizuPosed. */
    private static final String PREFS_FILE = "shizuposed_settings.xml";

    /** The database file name used by ShizuPosed. */
    private static final String DB_FILE = "modules_config.db";

    /**
     * The MODULE-signing keystore. User state; migrated.
     * Distinct from cloak-install.p12 (the per-install cloak key).
     */
    private static final String MODULE_KEYSTORE_FILE = "keystore.bks";

    /**
     * The PER-INSTALL cloak signing key. Generated on the first
     * cloak, carried across every subsequent Hide/Unhide so the
     * signature is stable within an install cycle.
     */
    private static final String CLOAK_KEYSTORE_FILE = "cloak-install.p12";

    private ManagerMigrate() {}

    public static File createMigrateZip(Context context, File dest) throws Exception {
        File parent = dest.getParentFile();
        if (parent != null) parent.mkdirs();
        if (dest.exists() && !dest.delete()) {
            throw new IllegalStateException("Could not delete stale migrate zip: " + dest);
        }

        try {
            File db = context.getDatabasePath(DB_FILE);
            if (db.exists()) {
                SQLiteDatabase sqlite = SQLiteDatabase.openDatabase(
                        db.getPath(), null, SQLiteDatabase.OPEN_READONLY);
                try {
                    android.database.Cursor c = sqlite.rawQuery(
                            "PRAGMA wal_checkpoint(FULL)", null);
                    try {
                        c.moveToFirst();
                    } finally {
                        c.close();
                    }
                } finally {
                    sqlite.close();
                }
            }
        } catch (Throwable t) {
            Log.w(TAG, "wal_checkpoint failed: " + t.getMessage());
        }

        try (ZipOutputStream zos = new ZipOutputStream(
                new BufferedOutputStream(new FileOutputStream(dest)))) {

            putFile(zos, ENTRY_PREFS,
                new File(context.getApplicationInfo().dataDir,
                    "shared_prefs/" + PREFS_FILE));

            putFile(zos, ENTRY_MODULE_KEYSTORE,
                new File(context.getFilesDir(), MODULE_KEYSTORE_FILE));

            // Carry the per-install cloak signing key across the
            // cloak. If the file doesn't exist (e.g. a standard
            // install that hasn't cloaked yet, being Unhidden from
            // a corrupt state), the entry is skipped — the
            // cloaked side will generate a fresh key on its next
            // cloak. The normal path always has this file by the
            // time a cloak is started, because ManagerCloak's
            // rebuildSelf generates it before the manifest patch.
            putFile(zos, ENTRY_CLOAK_KEYSTORE,
                new File(context.getFilesDir(), CLOAK_KEYSTORE_FILE));

            putFile(zos, ENTRY_DB,
                context.getDatabasePath(DB_FILE));
            putFile(zos, ENTRY_DB_WAL,
                new File(context.getDatabasePath(DB_FILE).getPath() + "-wal"));
            putFile(zos, ENTRY_DB_SHM,
                new File(context.getDatabasePath(DB_FILE).getPath() + "-shm"));
        }

        return dest;
    }

    private static void putFile(ZipOutputStream zos, String entryName, File file)
            throws Exception {
        if (!file.exists()) return;
        zos.putNextEntry(new ZipEntry(entryName));
        try (FileInputStream fis = new FileInputStream(file)) {
            byte[] buf = new byte[8192];
            int n;
            while ((n = fis.read(buf)) > 0) zos.write(buf, 0, n);
        }
        zos.closeEntry();
    }

    /**
     * If this install came from a cloak flow, restore the previous
     * package's settings, signing keystores, and module DB. No-op
     * on a normal install (no migrate asset in the APK).
     */
    public static void importIfNeeded(Context context) {
        File marker = new File(context.getFilesDir(), MARKER);
        if (marker.exists()) return;

        File apk = new File(context.getApplicationInfo().sourceDir);
        if (!apk.exists()) return;

        try (ZipFile zip = new ZipFile(apk)) {
            ZipEntry entry = zip.getEntry(ManagerCloak.MIGRATE_ASSET_PATH);
            if (entry == null) {
                context.getFilesDir().mkdirs();
                marker.createNewFile();
                return;
            }
            Log.i(TAG, "Importing migrate payload from manager APK");
            try (ZipInputStream zis = new ZipInputStream(zip.getInputStream(entry))) {
                ZipEntry e = zis.getNextEntry();
                while (e != null) {
                    String name = e.getName();
                    if (ENTRY_PREFS.equals(name)) {
                        write(zis, new File(context.getApplicationInfo().dataDir,
                            "shared_prefs/" + PREFS_FILE));
                    } else if (ENTRY_MODULE_KEYSTORE.equals(name)) {
                        context.getFilesDir().mkdirs();
                        write(zis, new File(context.getFilesDir(), MODULE_KEYSTORE_FILE));
                    } else if (ENTRY_CLOAK_KEYSTORE.equals(name)) {
                        context.getFilesDir().mkdirs();
                        File dest = new File(context.getFilesDir(), CLOAK_KEYSTORE_FILE);
                        write(zis, dest);
                        // Owner-only, matching what ManagerCloak does
                        // when it generates the key.
                        dest.setReadable(true, true);
                        dest.setWritable(true, true);
                    } else if (ENTRY_DB.equals(name)) {
                        write(zis, context.getDatabasePath(DB_FILE));
                    } else if (ENTRY_DB_WAL.equals(name)) {
                        write(zis, new File(context.getDatabasePath(DB_FILE).getPath() + "-wal"));
                    } else if (ENTRY_DB_SHM.equals(name)) {
                        write(zis, new File(context.getDatabasePath(DB_FILE).getPath() + "-shm"));
                    }
                    zis.closeEntry();
                    e = zis.getNextEntry();
                }
            }
            context.getFilesDir().mkdirs();
            marker.createNewFile();
            Log.i(TAG, "Migrate import completed");
        } catch (Throwable t) {
            Log.e(TAG, "Failed to import migrate payload", t);
        }
    }

    private static void write(ZipInputStream zis, File out) throws Exception {
        File parent = out.getParentFile();
        if (parent != null) parent.mkdirs();
        try (FileOutputStream fos = new FileOutputStream(out)) {
            byte[] buf = new byte[8192];
            int n;
            while ((n = zis.read(buf)) > 0) fos.write(buf, 0, n);
        }
    }
}